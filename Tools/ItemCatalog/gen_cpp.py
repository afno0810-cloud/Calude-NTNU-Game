"""Writes Source/Gloshaugen/Private/GSItemCatalog.gen.inl from catalog.py (+ model_metrics.json).
Run after editing the catalog:  python Tools/ItemCatalog/gen_cpp.py"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import catalog  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "Source", "Gloshaugen", "Private", "GSItemCatalog.gen.inl")
metrics = json.load(open(os.path.join(HERE, "model_metrics.json")))


def s(text):
    """C++ wide string literal, non-ASCII as \\u escapes (MSVC-safe)."""
    out = []
    for ch in text:
        if ch == '"' or ch == "\\":
            out.append("\\" + ch)
        elif ord(ch) < 128:
            out.append(ch)
        else:
            out.append("\\u%04X" % ord(ch))
    return 'TEXT("' + "".join(out) + '")'


def f(x):
    t = f"{float(x):.6g}"
    if "." not in t and "e" not in t:
        t += ".0"
    return t + "f"


# First-person placement per weapon class: (hip x, y, z offset), aim distance in front of the eye (cm)
FP = {
    "Pistol": ((32, 12, -15), 26), "SMG": ((26, 12, -18), 18), "Rifle": ((24, 12, -21), 16),
    "Sniper": ((22, 12, -21), 9), "Shotgun": ((24, 12, -21), 16), "LMG": ((22, 14, -24), 16),
    "Launcher": ((14, 16, -16), 6), "Bow": ((22, 12, -20), 14), "Melee": ((36, 20, -24), 36),
}
MAXSTACK = dict(Food=5, Drug=3, Medicine=5, Throwable=4, Gadget=1, Weapon=1, Armor=1, Helmet=1)

lines = ["// GENERATED by Tools/ItemCatalog/gen_cpp.py from catalog.py. Do not edit by hand.", "#pragma once", "",
         "static void GSBuildCatalog(TArray<FGSItemDef>& Items, TArray<FGSEffectDef>& Effects)", "{"]

MODKEYS = dict(speed="Speed", stamina_drain="StaminaDrain", stamina_regen="StaminaRegen", recoil="Recoil",
               spread="Spread", damage="Damage", taken="Taken", jump="Jump", reload="Reload", hunger="Hunger",
               thirst="Thirst", regen="Regen", drain="Drain", lifesteal="Lifesteal")
FLAGS = dict(nightvision="bNightVision", wallhack="bWallhack", phoenix="bPhoenix", silent="bSilent",
             flashimmune="bFlashImmune", ghost="bGhost", glide="bGlide", numb="bNumb", cough="bCough")
DRUGCLASS = dict(stim="Stimulant", opioid="Opioid", depressant="Depressant", alcohol="Alcohol", nicotine="Nicotine",
                 caffeine="Caffeine", cannabis="Cannabis", antidote="Antidote")

# ---------------------------------------------------------------- checks (stop before anything is written)
EFFECTS, ITEMS = catalog.EFFECTS, catalog.ITEMS
ids = {it["id"] for it in ITEMS}
# (1) every effect and after exists
for it in ITEMS:
    assert not it.get("effect") or it["effect"] in EFFECTS, ("unknown effect", it["id"], it.get("effect"))
for k, e in EFFECTS.items():
    assert not e.get("after") or e["after"] in EFFECTS, ("unknown after", k)
    assert e.get("cls") is None or e["cls"] in DRUGCLASS, ("unknown cls", k, e.get("cls"))
    assert int(e.get("visual", 0)) <= 11, ("unknown visual", k)


def looted(it):
    return it.get("loot", True) is not False


# (2) every drug in loot has an effect with a drug class
for it in ITEMS:
    if it["cat"] == "Drug" and looted(it):
        assert EFFECTS[it["effect"]].get("cls"), ("drug without cls", it["id"])
# (3) the ids Kamp's code uses
for k in ("Foniks", "Glide", "Avslort", "Blendet", "Matforgiftning", "Smertestillende", "Brennende", "Sjokk", "Adrenalin", "Turbo"):
    assert k in EFFECTS, ("Kamp uses effect", k)
for k in ("Plaster", "Bandage", "Medkit", "SurgeryKit"):
    assert k in ids, ("Kamp uses item", k)
# (4) food and drugs never heal
for it in ITEMS:
    if it["cat"] in ("Food", "Drug"):
        assert it.get("heal", 0) == 0, ("food/drug heals", it["id"])
# (5) nothing in loot is supernatural (the effect and the side effects after it)
SUPER = ("lifesteal", "ghost", "wallhack", "phoenix", "nightvision", "flashimmune")
for it in ITEMS:
    if not looted(it) or not it.get("effect"):
        continue
    k, seen = it["effect"], set()
    while k and k not in seen:
        seen.add(k)
        e = EFFECTS[k]
        assert e.get("taken", 1) >= 1 and e.get("damage", 1) <= 1, ("supernatural taken/damage", it["id"], k)
        assert e.get("regen", 0) <= 0 or k in ("Stell", "Kirurgi"), ("regen in loot", it["id"], k)
        assert not any(e.get(x) for x in SUPER), ("supernatural flag in loot", it["id"], k)
        k = e.get("after")

for key, e in catalog.EFFECTS.items():
    lines.append(f"\t{{ FGSEffectDef& E = Effects.AddDefaulted_GetRef(); E.Id = FName(TEXT(\"{key}\")); E.Name = {s(e['name'])}; E.Duration = {f(e['dur'])};")
    body = []
    for k, v in e.items():
        if k in MODKEYS:
            body.append(f"E.Mods.{MODKEYS[k]} = {f(v)};")
        elif k in FLAGS:
            body.append(f"E.Mods.{FLAGS[k]} = true;")
        elif k == "visual":
            body.append(f"E.Mods.Visual = {int(v)};")
        elif k == "after":
            body.append(f"E.After = FName(TEXT(\"{v}\"));")
        elif k == "onset" and v:
            body.append(f"E.Onset = {f(v)};")
        elif k == "fade" and v:
            body.append(f"E.Fade = {f(v)};")
        elif k == "load" and v:
            body.append(f"E.Load = {f(v)};")
        elif k == "cls":
            body.append(f"E.Class = EGSDrugClass::{DRUGCLASS[v]};")
    lines.append("\t\t" + " ".join(body) + " }")

lines.append("")
for it in catalog.ITEMS:
    met = metrics.get(it["id"], {})
    mesh = met.get("mesh", f"SM_{it['id']}")
    L = [f"\t{{ FGSItemDef& D = Items.AddDefaulted_GetRef(); D.Id = FName(TEXT(\"{it['id']}\")); D.Name = {s(it['name'])};",
         f"D.Desc = {s(it.get('desc', ''))}; D.Cat = EGSItemCat::{it['cat']}; D.Rarity = EGSRarity::{it['rarity']};",
         f"D.MeshPath = TEXT(\"/Game/Models/{mesh}.{mesh}\"); D.MaxStack = {MAXSTACK[it['cat']]};"]
    cat = it["cat"]
    if cat == "Weapon":
        cls = it["cls"]
        hip, aimx = FP[cls]
        sight = met.get("sight", 0.05) * 100
        muzzle = met.get("muzzle", 0.5) * 100
        mode = dict(hitscan="Hitscan", pellets="Pellets", projectile="Projectile", melee="Melee")[it["mode"]]
        L.append(f"FGSWeaponStats& W = D.W; W.Class = EGSWeaponClass::{cls}; W.Mode = EGSFireMode::{mode};")
        L.append(f"W.Damage = {f(it['dmg'])}; W.FireInterval = {f(it['interval'])}; W.bAutomatic = {'true' if it['auto'] else 'false'};")
        L.append(f"W.MagSize = {it['mag']}; W.StartReserve = {it['reserve']}; W.MaxReserve = {it['max_reserve']}; W.ReloadTime = {f(it['reload'])};")
        L.append(f"W.Range = {f(it['range'] * 100)}; W.HipSpread = {f(it['hip'])}; W.AimSpread = {f(it['aim'])}; W.RecoilPitch = {f(it['recoil'])}; W.AimFOV = {f(it['fov'])};")
        L.append(f"W.HeadshotMultiplier = {f(it.get('headshot', 2.0))}; W.Pellets = {it.get('pellets', 1)}; W.MeleeDamage = {f(it.get('melee_dmg', 25))};")
        if it["mode"] == "projectile":
            L.append(f"W.ProjSpeed = {f(it['proj_speed'] * 100)}; W.ProjGravity = {f(it['proj_gravity'])}; W.Radius = {f(it['radius'] * 100)};")
        if it.get("silent"):
            L.append("W.bSilent = true;")
        if it.get("caliber"):
            L.append(f"W.Caliber = FName(TEXT(\"{it['caliber']}\"));")
        aimz = -sight if cls != "Melee" else -20
        aimy = 0 if cls != "Melee" else 14
        bore = met.get("bore", met.get("sight", 0.05) - 0.05) * 100
        L.append(f"W.BoreZ = {f(bore)}; W.SightZ = {f(sight)};")
        L.append(f"W.MuzzleX = {f(muzzle)}; W.FPHip = FVector({hip[0]}.f, {hip[1]}.f, {hip[2]}.f); W.FPAim = FVector({aimx}.f, {aimy}.f, {f(aimz)});")
    elif cat in ("Armor", "Helmet"):
        L.append(f"D.Armor = {f(it['armor'])}; D.Absorb = {f(it['absorb'])}; D.SpeedMul = {f(it['speed'])};")
    elif cat in ("Food", "Drug", "Medicine"):
        L.append(f"D.UseTime = {f(it.get('use', 2))}; D.Heal = {f(it.get('heal', 0))}; D.Hunger = {f(it.get('hunger', 0))}; D.Thirst = {f(it.get('thirst', 0))};")
        L.append(f"D.StaminaGain = {f(it.get('stamina', 0))}; D.Poison = {f(it.get('poison', 0))}; D.Effect = FName(TEXT(\"{it.get('effect', '')}\"));")
        anim = it.get("anim") or (it.get("model") or {}).get("arch", "")
        L.append(f"D.Treat = {f(it.get('treat', 0))}; D.UseAnim = FName(TEXT(\"{anim}\"));")
        if it.get("kind"):
            L.append(f"D.Kind = FName(TEXT(\"{it['kind']}\"));")
    elif cat == "Throwable":
        L.append(f"D.Kind = FName(TEXT(\"{it['kind']}\")); D.UseTime = {f(it['use'])}; D.ThrowDamage = {f(it['dmg'])}; D.ThrowRadius = {f(it['radius'] * 100)}; D.Fuse = {f(it['fuse'])};")
    elif cat == "Gadget":
        L.append(f"D.Kind = FName(TEXT(\"{it['kind']}\")); D.UseTime = {f(it['use'])}; D.Slots = {it.get('slots', 0)}; D.Charges = {it.get('charges', 1)};")
        if it.get("effect"):
            L.append(f"D.Effect = FName(TEXT(\"{it['effect']}\"));")
        if it["kind"] in ("ammo", "plate", "grapple") or it["kind"].startswith("ammotype_"):
            L.append("D.MaxStack = 3;")
        if it["kind"] in ("caliber", "filament"):
            L.append("D.MaxStack = 10;")
        if it.get("caliber"):
            L.append(f"D.Caliber = FName(TEXT(\"{it['caliber']}\")); D.Rounds = {it.get('rounds', 0)};")
    if not looted(it):
        L.append("D.bNoLoot = true;")
    lines.append("\n\t\t".join(L) + " }")
lines.append("}")
open(OUT, "w", newline="\n").write("\n".join(lines) + "\n")
print("wrote", OUT, len(catalog.ITEMS), "items")
